"""Sanity tests for ``scripts/generate_test_inventory.py``.

The script parses every ``tests_rust/test_*.py`` file via ``ast`` and
emits a markdown catalog at ``docs/RUST_TEST_INVENTORY.md``. These
tests pin the contract:

* the script's ``main()`` runs end-to-end without error;
* the generated doc carries the auto-gen header, the file-summary
  table, and the canonical anchor files (``test_setup.py``,
  ``test_legal.py``);
* the total test count matches what a fresh ``ast`` walk of the live
  ``tests_rust/`` tree finds (catches off-by-one regressions in the
  collector);
* a small synthetic-tree smoke confirms the collector picks up
  module docstrings + per-test docstrings correctly.

This test does NOT depend on the Rust extension — the script is a
pure Python AST walk.
"""

from __future__ import annotations

import ast
import importlib.util
import sys
from pathlib import Path

import pytest


REPO_ROOT = Path(__file__).resolve().parents[1]
SCRIPT_PATH = REPO_ROOT / "scripts" / "generate_test_inventory.py"
DOC_PATH = REPO_ROOT / "docs" / "RUST_TEST_INVENTORY.md"
TESTS_RUST_DIR = REPO_ROOT / "tests_rust"


def _load_script():
    """Import the script module under a stable name without invoking
    its ``main()``. Returns the loaded module."""
    spec = importlib.util.spec_from_file_location(
        "_generate_test_inventory_under_test", SCRIPT_PATH
    )
    assert spec is not None and spec.loader is not None
    mod = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = mod
    spec.loader.exec_module(mod)
    return mod


def _count_top_level_tests(path: Path) -> int:
    """Independent test-counter — uses ``ast`` directly so we don't
    just verify the script against itself."""
    tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    n = 0
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            if node.name.startswith("test_"):
                n += 1
    return n


def test_script_runs_and_writes_doc():
    """``main()`` runs to completion and writes the target markdown
    file with the auto-gen header + expected canonical anchor files."""
    mod = _load_script()
    rc = mod.main([])
    assert rc == 0
    assert DOC_PATH.exists(), f"expected {DOC_PATH} to exist after main()"
    text = DOC_PATH.read_text(encoding="utf-8")
    assert text.startswith(
        "Generated by `scripts/generate_test_inventory.py`"
    ), "auto-generated header missing — script may have been short-circuited"
    assert "# Rust-engine test inventory" in text
    # The canonical anchor files — if these are missing from the
    # generated doc, the collector glob is broken.
    assert "`test_setup.py`" in text
    assert "`test_legal.py`" in text


def test_total_test_count_matches_independent_ast_walk():
    """The script's collector must produce the same total test count
    as an independent ``ast`` walk of the live tests_rust/ tree."""
    mod = _load_script()
    files = mod.collect_test_files(TESTS_RUST_DIR)
    script_total = sum(len(f.tests) for f in files)

    independent_total = sum(
        _count_top_level_tests(p)
        for p in sorted(TESTS_RUST_DIR.glob("test_*.py"))
        if p.name not in mod.NON_TEST_FILES
    )

    assert script_total == independent_total, (
        f"collector reported {script_total} tests but independent ast walk "
        f"reported {independent_total}"
    )
    # Magnitude check — tests_rust/ has many hundreds of tests today;
    # if this drops below ~50 something is structurally wrong.
    assert script_total > 50, (
        f"unexpectedly low test count from collector: {script_total}"
    )


def test_synthetic_tree_collector(tmp_path: Path):
    """Smoke a tiny synthetic ``tests_rust/`` tree: the collector must
    pick up the module docstring's first line, two ``test_*`` function
    docstrings, and ignore a non-test helper function."""
    mod = _load_script()

    # File 1: has a module docstring + two tests, one with docstring.
    (tmp_path / "test_alpha.py").write_text(
        '"""Alpha primitive — first slice."""\n'
        "\n"
        "def test_one():\n"
        '    """Checks one thing."""\n'
        "    assert True\n"
        "\n"
        "def test_two():\n"
        "    assert True\n"
        "\n"
        "def helper_not_a_test():\n"
        "    pass\n",
        encoding="utf-8",
    )
    # File 2: no module docstring, one test.
    (tmp_path / "test_beta.py").write_text(
        "def test_only():\n"
        '    """Only test."""\n'
        "    assert True\n",
        encoding="utf-8",
    )
    # Decoy: conftest.py must be skipped.
    (tmp_path / "conftest.py").write_text(
        "def test_decoy():\n    pass\n", encoding="utf-8"
    )

    files = mod.collect_test_files(tmp_path)
    by_name = {f.path.name: f for f in files}

    assert set(by_name) == {"test_alpha.py", "test_beta.py"}, (
        "conftest.py leaked into collector output, or a test file went missing"
    )

    alpha = by_name["test_alpha.py"]
    assert alpha.module_docstring_first_line == "Alpha primitive — first slice."
    assert [t.name for t in alpha.tests] == ["test_one", "test_two"]
    assert alpha.tests[0].docstring_first_line == "Checks one thing."
    assert alpha.tests[1].docstring_first_line == ""

    beta = by_name["test_beta.py"]
    assert beta.module_docstring_first_line == ""
    assert [t.name for t in beta.tests] == ["test_only"]
    assert beta.tests[0].docstring_first_line == "Only test."


def test_stdout_mode_prints_and_does_not_write(tmp_path: Path, capsys):
    """``--stdout`` must print the markdown and NOT write to the
    default output path (when the output path is redirected to a
    tmp location that we then verify is empty)."""
    mod = _load_script()
    out = tmp_path / "should_not_exist.md"
    rc = mod.main(["--stdout", "--output", str(out)])
    assert rc == 0
    captured = capsys.readouterr().out
    assert "# Rust-engine test inventory" in captured
    assert not out.exists(), (
        f"--stdout mode should not write the output file, but {out} exists"
    )
